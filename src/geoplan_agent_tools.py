    def create_role_tool_groups(
        self,
    ) -> dict[str, list[Any]]:
        """
        Return LlamaIndex FunctionTool lists grouped by specialist-agent role.
        """
        tools = self.create_llamaindex_tools()
        return {
            role: [
                tools[name]
                for name in names
            ]
            for role, names in self.role_tool_names().items()
        }

    def save_tool_manifest(
        self,
        path: str | Path | None = None,
    ) -> Path:
        """
        Save a JSON manifest describing tool names and recommended agent roles.
        """
        target = Path(
            path
            or (
                self.output_dir
                / "agent_tool_manifest.json"
            )
        )

        target.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        manifest = {
            "project_root": str(self.project_root),
            "tool_names": list(
                self.create_llamaindex_tools().keys()
            ),
            "role_tool_names": self.role_tool_names(),
            "file_status": self.file_status(),
        }

        with target.open(
            "w",
            encoding="utf-8",
        ) as file:
            json.dump(
                _json_safe(manifest),
                file,
                indent=2,
            )

        return target
